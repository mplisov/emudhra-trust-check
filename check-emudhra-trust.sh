OS=$(uname -s)
TMP=$(mktemp -d "${TMPDIR:-/tmp}/emudhra.XXXXXX") || { echo "mktemp failed" >&2; exit 2; }
trap 'rm -rf "$TMP"' EXIT
fp_of() { openssl x509 -in "$1" -noout -fingerprint -sha256 2>/dev/null | sed 's/.*=//; s/://g' | tr a-f A-F; }

# Split the embedded PEM stream into $TMP/<SHA256>.pem files
embedded_pems | awk -v d="$TMP" '/-----BEGIN CERTIFICATE-----/{n++; f=sprintf("%s/split-%03d.pem",d,n)}
                 f{print > f} /-----END CERTIFICATE-----/{close(f); f=""}'
for f in "$TMP"/split-*.pem; do
  [ -e "$f" ] || continue
  fp=$(fp_of "$f"); if [ -n "$fp" ]; then mv "$f" "$TMP/$fp.pem"; else rm -f "$f"; fi
done

# Every listed fingerprint must be present, or the embedded data was damaged
bad=0
while IFS='|' read -r fp use cn issuer; do
  [ -z "$fp" ] && continue
  [ -s "$TMP/$fp.pem" ] || { echo "embedded cert missing or corrupted: $cn ($issuer) $fp" >&2; bad=1; }
done <<<"$CERTS"
[ "$bad" = 1 ] && { echo "Aborting: this copy of the script is damaged." >&2; exit 2; }

# Does this openssl support on-the-fly CRL download? (OpenSSL 1.1+, not LibreSSL)
CRL_OK=0; [ "$ONLINE" = 1 ] && openssl verify -help 2>&1 | grep -q crl_download && CRL_OK=1
MAC_OPTS="-L"; [ "$ONLINE" = 1 ] && MAC_OPTS="-L -R ocsp"

echo "OpenSSL: $(openssl version)   default store: $(openssl version -d | sed 's/.*"\(.*\)"/\1/')"
[ "$OS" = Darwin ] && echo "macOS detected: also checking the system verifier (security verify-cert)"
echo "Certificates: 16 embedded, fingerprints verified"
if [ "$ONLINE" = 1 ]; then echo "Mode: online revocation checks enabled (-r)"
else echo "Mode: offline (no network access; pass -r to also check revocation)"; fi
echo
printf '%-20s %-4s %-34s %-10s %-10s %s\n' "INTERMEDIATE" "USE" "ISSUER" "OPENSSL" "+CRL" "$([ "$OS" = Darwin ] && echo MACOS)"

tls_accept=0; tls_revoked=0; mac_accept=0
while IFS='|' read -r fp use cn issuer; do
  [ -z "$fp" ] && continue
  pem="$TMP/$fp.pem"

  # 1) default OpenSSL trust store, no revocation (how most Linux tools behave)
  if openssl verify -purpose any "$pem" >/dev/null 2>&1; then r1=ACCEPTED; [ "$use" = TLS ] && tls_accept=$((tls_accept+1)); else r1=rejected; fi

  # 2) same, with CRL checking (only with -r)
  r2=n/a
  if [ "$CRL_OK" = 1 ] && [ "$r1" = ACCEPTED ]; then
    o=$(openssl verify -purpose any -crl_check -crl_download "$pem" 2>&1)
    if [ $? -eq 0 ]; then r2=ACCEPTED
    elif grep -qi revoked <<<"$o"; then r2=revoked; [ "$use" = TLS ] && tls_revoked=$((tls_revoked+1))
    else r2=crl-error; fi
  fi

  # 3) macOS platform verifier (includes Apple's locally cached revocation data)
  r3=""
  if [ "$OS" = Darwin ]; then
    # shellcheck disable=SC2086
    if security verify-cert -c "$pem" -p basic $MAC_OPTS -q >/dev/null 2>&1; then r3=ACCEPTED; mac_accept=$((mac_accept+1)); else r3=rejected; fi
  fi
  printf '%-20s %-4s %-34s %-10s %-10s %s\n' "${cn#EM }" "$use" "$issuer" "$r1" "$r2" "$r3"
done <<<"$CERTS"

echo
echo "OPENSSL = chains to a root in the default OpenSSL store, no revocation check."
echo "+CRL    = same, but downloading the issuer's CRL ('revoked' = blocked if a client checks)."
if [ "$ONLINE" = 0 ]; then echo "          (offline mode: +CRL is n/a; run with -r to fill it in)"
elif [ "$CRL_OK" = 0 ]; then echo "          (this openssl can't download CRLs, so +CRL is n/a)"; fi
echo

if [ "$tls_accept" -gt 0 ]; then
  echo "RESULT: $tls_accept compromised TLS intermediate(s) chain to a trusted root in the OpenSSL store."
  echo "        Tools that use this store and don't check revocation (most curl/wget/python/"
  echo "        openssl-based clients) would accept forged certs for any domain via these chains."
  echo "        Removing the emSign roots alone won't fix the Sectigo AAA cross-signed paths."
  if [ "$tls_revoked" -gt 0 ]; then
    echo "        $tls_revoked of them are revoked in the issuer's CRL: clients that check CRLs reject"
    echo "        them, but most OpenSSL-based tools don't check, so they are still exposed."
  fi
  rc=1
else
  echo "RESULT: none of the compromised TLS intermediates chain to a trusted root in the OpenSSL store."
  rc=0
fi
if [ "$OS" = Darwin ]; then
  if [ "$mac_accept" -gt 0 ]; then
    echo "macOS:  the system verifier ACCEPTED $mac_accept of them — Safari/Chrome/native apps may be exposed."; rc=1
  else
    echo "macOS:  the system verifier rejected all of them (Safari/Chrome/native apps/Go are protected)."
    echo "        The OPENSSL column only matters for LibreSSL/OpenSSL tools that read /etc/ssl/cert.pem."
  fi
fi
exit $rc
}

