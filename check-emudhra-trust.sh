#!/usr/bin/env bash
# check-emudhra-trust.sh — would this machine accept certificates issued by the
# eight compromised eMudhra intermediates (Oct 2026)?
#
# The bad keys belong to 8 intermediates ("EM {DV,OV,EV} TLS CA - G3B/G3C" and
# "EM OV CS CA - G3B/G3C"). Each exists twice: signed by an emSign G3 root AND
# cross-signed by Sectigo "AAA Certificate Services", which almost every trust
# store contains. Having emSign roots in your bundle is NOT the problem by itself;
# what matters is whether these intermediate certs chain to something you trust.
#
# Self-contained: all 16 certs are embedded at the end of this script and their
# SHA-256 fingerprints are re-checked on every run. No downloads, no network
# access (unless you pass -r), no files written outside a private temp dir.
# Needs only bash and openssl. Read-only.
#
# For each of the 16 certs, this script:
#   1. checks it chains to a trusted root with OpenSSL's default store
#      (what curl/wget/python/etc. on Linux use) — no revocation check,
#   2. with -r: checks again WITH CRL revocation checking (downloads CRLs),
#   3. on macOS, also asks the system verifier (security verify-cert), which is
#      what Safari/Chrome/native apps/Go use there. Local only; with -r it also
#      queries OCSP.
#
# Usage: ./check-emudhra-trust.sh [-r]
#        bash check-emudhra-trust.sh [-r]      (no exec bit needed)
#        bash -s -- [-r] < check-emudhra-trust.sh
#   -r   also check revocation online (the only thing that touches the network)
# Exit:  0 = not exposed, 1 = a compromised chain is accepted, 2 = error

# Started as "sh check-emudhra-trust.sh" (dash, busybox ash)? Re-run under bash.
if [ -z "${BASH_VERSION:-}" ]; then
  if command -v bash >/dev/null 2>&1 && [ -f "$0" ]; then exec bash "$0" "$@"; fi
  echo "This script needs bash (Alpine: apk add bash)." >&2; exit 2
fi

set -u
# Everything runs inside main(), called on the last line, so the whole file is
# parsed before anything executes (needed for "bash -s < script" to work).
