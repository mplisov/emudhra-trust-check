usage() {
  echo "Usage: $0 [-r]"
  echo "  Checks offline whether this machine trusts the 16 compromised eMudhra intermediate certs."
  echo "  -r   also check revocation online (CRL download; OCSP on macOS)"
}
ONLINE=0
while getopts "rh" o; do
  case $o in r) ONLINE=1;; h) usage; exit 0;; *) usage >&2; exit 2;; esac
